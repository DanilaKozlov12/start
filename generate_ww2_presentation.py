# ── helpers ────────────────────────────────────────────────────────────────

def rect(slide, l, t, w, h, fill, line=None):
    s = slide.shapes.add_shape(1, Inches(l), Inches(t), Inches(w), Inches(h))
    s.fill.solid()
    s.fill.fore_color.rgb = fill
    if line:
        s.line.color.rgb = line
    else:
        s.line.fill.background()
    return s


def tb(slide, text, l, t, w, h, size=16, bold=False, color=COLOR_DARK_GREY,
       align=PP_ALIGN.LEFT, italic=False, font="Calibri"):
    box = slide.shapes.add_textbox(Inches(l), Inches(t), Inches(w), Inches(h))
    tf = box.text_frame
    tf.word_wrap = True
    p = tf.paragraphs[0]
    p.alignment = align
    r = p.add_run()
    r.text = text
    r.font.size = Pt(size)
    r.font.bold = bold
    r.font.italic = italic
    r.font.color.rgb = color
    r.font.name = font
    return box


def bullets(slide, items, l, t, w, h, size=15, color=COLOR_DARK_GREY,
            char="◆", font="Calibri"):
    box = slide.shapes.add_textbox(Inches(l), Inches(t), Inches(w), Inches(h))
    tf = box.text_frame
    tf.word_wrap = True
    for i, item in enumerate(items):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.space_before = Pt(4)
        r = p.add_run()
        r.text = f"{char}  {item}"
        r.font.size = Pt(size)
        r.font.color.rgb = color
        r.font.name = font
    return box


def header(slide, title, h=1.4):
    rect(slide, 0, 0, 13.33, h, COLOR_DARK_RED)
